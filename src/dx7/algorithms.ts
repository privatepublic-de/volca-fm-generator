// The DX7's 32 algorithms. The routing table is MSFA's (music-synthesizer-for-android, fm_core.cc,
// Copyright 2012 Google Inc., Apache License 2.0): per algorithm, six operators in the order they are computed
// (OP6 first), each with flags for its input bus, output bus and feedback. Everything else here (the graph the
// generator and the drawings use) is derived from that table.

/** Bits 0–1: output bus (0 = the voice's output, 1/2 = scratch buses); bit 2: add to the bus instead of
 *  overwriting it; bits 4–5: input bus (0 = none); bit 6: takes feedback in; bit 7: sends feedback out. */
const FLAGS: readonly (readonly number[])[] = [
  [0xc1, 0x11, 0x11, 0x14, 0x01, 0x14], // 1
  [0x01, 0x11, 0x11, 0x14, 0xc1, 0x14], // 2
  [0xc1, 0x11, 0x14, 0x01, 0x11, 0x14], // 3
  [0x41, 0x11, 0x94, 0x01, 0x11, 0x14], // 4
  [0xc1, 0x14, 0x01, 0x14, 0x01, 0x14], // 5
  [0x41, 0x94, 0x01, 0x14, 0x01, 0x14], // 6
  [0xc1, 0x11, 0x05, 0x14, 0x01, 0x14], // 7
  [0x01, 0x11, 0xc5, 0x14, 0x01, 0x14], // 8
  [0x01, 0x11, 0x05, 0x14, 0xc1, 0x14], // 9
  [0x01, 0x05, 0x14, 0xc1, 0x11, 0x14], // 10
  [0xc1, 0x05, 0x14, 0x01, 0x11, 0x14], // 11
  [0x01, 0x05, 0x05, 0x14, 0xc1, 0x14], // 12
  [0xc1, 0x05, 0x05, 0x14, 0x01, 0x14], // 13
  [0xc1, 0x05, 0x11, 0x14, 0x01, 0x14], // 14
  [0x01, 0x05, 0x11, 0x14, 0xc1, 0x14], // 15
  [0xc1, 0x11, 0x02, 0x25, 0x05, 0x14], // 16
  [0x01, 0x11, 0x02, 0x25, 0xc5, 0x14], // 17
  [0x01, 0x11, 0x11, 0xc5, 0x05, 0x14], // 18
  [0xc1, 0x14, 0x14, 0x01, 0x11, 0x14], // 19
  [0x01, 0x05, 0x14, 0xc1, 0x14, 0x14], // 20
  [0x01, 0x14, 0x14, 0xc1, 0x14, 0x14], // 21
  [0xc1, 0x14, 0x14, 0x14, 0x01, 0x14], // 22
  [0xc1, 0x14, 0x14, 0x01, 0x14, 0x04], // 23
  [0xc1, 0x14, 0x14, 0x14, 0x04, 0x04], // 24
  [0xc1, 0x14, 0x14, 0x04, 0x04, 0x04], // 25
  [0xc1, 0x05, 0x14, 0x01, 0x14, 0x04], // 26
  [0x01, 0x05, 0x14, 0xc1, 0x14, 0x04], // 27
  [0x04, 0xc1, 0x11, 0x14, 0x01, 0x14], // 28
  [0xc1, 0x14, 0x01, 0x14, 0x04, 0x04], // 29
  [0x04, 0xc1, 0x11, 0x14, 0x04, 0x04], // 30
  [0xc1, 0x14, 0x04, 0x04, 0x04, 0x04], // 31
  [0xc4, 0x04, 0x04, 0x04, 0x04, 0x04], // 32
]

/** One operator's step in an algorithm, in computing order. */
export interface RouteStep {
  /** 1–6 as the DX7 numbers them */
  op: number
  inBus: number
  outBus: number
  add: boolean
  fbIn: boolean
  fbOut: boolean
}

export interface Algorithm {
  /** 1–32 */
  number: number
  /** OP6 … OP1: what the engine runs */
  steps: readonly RouteStep[]
  /** the operators heard directly */
  carriers: readonly number[]
  /** per operator (index 1–6): the operators that modulate it */
  modulators: readonly (readonly number[])[]
  /** feedback from one operator's output into another's (or its own) input */
  feedback: { from: number; to: number }
}

function decode(index: number): Algorithm {
  const steps = FLAGS[index].map((f, i) => ({
    op: 6 - i, outBus: f & 3, add: (f & 4) !== 0, inBus: (f >> 4) & 3, fbIn: (f & 0x40) !== 0, fbOut: (f & 0x80) !== 0,
  }))
  // Follow the buses symbolically: which operators' outputs each bus holds when the next one reads it.
  const buses: number[][] = [[], [], []]
  const modulators: number[][] = [[], [], [], [], [], [], []]
  for (const s of steps) {
    if (s.inBus) modulators[s.op] = [...buses[s.inBus]].sort()
    buses[s.outBus] = s.add ? [...buses[s.outBus], s.op] : [s.op]
  }
  const from = steps.find((s) => s.fbOut)!.op
  const to = steps.find((s) => s.fbIn)!.op
  return { number: index + 1, steps, carriers: [...buses[0]].sort(), modulators, feedback: { from, to } }
}

export const ALGORITHMS: readonly Algorithm[] = FLAGS.map((_, i) => decode(i))

/** By the byte's value (0–31). */
export const algorithmOf = (byte: number) => ALGORITHMS[byte & 31]
